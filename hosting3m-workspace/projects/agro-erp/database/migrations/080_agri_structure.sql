-- 1) Shared helpers ----------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_agri_utc_now()
RETURNS timestamp
LANGUAGE sql
STABLE
AS $$ SELECT (now() AT TIME ZONE 'UTC') $$;

CREATE OR REPLACE FUNCTION public.fn_agri_today_cdmx()
RETURNS date
LANGUAGE sql
STABLE
AS $$ SELECT (now() AT TIME ZONE 'America/Mexico_City')::date $$;

-- Role of an active user in an active membership of the company; NULL when there is none.
CREATE OR REPLACE FUNCTION public.fn_agri_actor_role(p_tenant_id integer, p_email text)
RETURNS text
LANGUAGE sql
STABLE
AS $$
    SELECT upper(uc.role)
      FROM public.user_companies uc
      JOIN public.users u ON lower(u.email) = lower(uc.email)
     WHERE lower(uc.email) = lower(btrim(coalesce(p_email, '')))
       AND uc.id_company = p_tenant_id
       AND uc.is_active IS TRUE
       AND u.is_active IS NOT FALSE
     LIMIT 1
$$;

CREATE OR REPLACE FUNCTION public.fn_agri_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := public.fn_agri_utc_now();
    RETURN NEW;
END;
$$;

-- Session settings used by the procedures (SET LOCAL semantics); '' and NULL both mean "not set".
CREATE OR REPLACE FUNCTION public.fn_agri_setting(p_name text)
RETURNS text
LANGUAGE sql
STABLE
AS $$ SELECT NULLIF(btrim(coalesce(current_setting(p_name, true), '')), '') $$;

