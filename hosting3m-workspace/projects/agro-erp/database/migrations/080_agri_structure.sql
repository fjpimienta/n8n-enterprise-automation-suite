CREATE OR REPLACE VIEW public.vw_agri_lot_summary AS
SELECT
    l.id,
    l.id_company,
    l.plantation_id,
    p.plantation_code,
    p.plantation_name,
    p.is_active                                  AS plantation_is_active,
    l.lot_code,
    l.lot_name,
    l.is_active,
    l.area_ha,
    l.planting_date,
    l.planting_date_is_approx,
    l.variety_id,
    v.variety_code,
    v.variety_name,
    l.planting_pattern,
    l.spacing_m,
    l.design_density_plants_ha,
    l.water_regime,
    l.soil_type,
    l.tenure,
    l.lessor_name,
    -- A lot without its own tenure inherits the plantation's (tenure and lessor always travel together).
    coalesce(l.tenure, p.tenure)                 AS effective_tenure,
    CASE WHEN l.tenure IS NOT NULL THEN l.lessor_name ELSE p.lessor_name END AS effective_lessor_name,
    a.age_years,
    -- ⚠️ Stage cut-offs are ORIENTATIVE, pending confirmation with the client (completed years since
    -- planting_date): INMADURA < 3, INICIO_PRODUCCION 3–7, PRODUCCION_PLENA 8–20,
    -- PRODUCCION_DECLINANTE 21–25, RENOVACION > 25. SIN_FECHA when planting_date is unknown.
    CASE
        WHEN a.age_years IS NULL THEN 'SIN_FECHA'
        WHEN a.age_years < 3     THEN 'INMADURA'
        WHEN a.age_years <= 7    THEN 'INICIO_PRODUCCION'
        WHEN a.age_years <= 20   THEN 'PRODUCCION_PLENA'
        WHEN a.age_years <= 25   THEN 'PRODUCCION_DECLINANTE'
        ELSE 'RENOVACION'
    END                                          AS productive_stage,
    coalesce(r.active_rows, 0)                   AS active_rows,
    coalesce(r.planting_positions, 0)            AS planting_positions,
    coalesce(r.alive_plants, 0)                  AS alive_plants,
    coalesce(r.planting_positions, 0) - coalesce(r.alive_plants, 0) AS missing_plants,
    round(coalesce(r.alive_plants, 0) / l.area_ha, 1)              AS real_density_plants_ha,
    CASE WHEN l.design_density_plants_ha > 0
         THEN round(100.0 * coalesce(r.alive_plants, 0) / l.area_ha / l.design_density_plants_ha, 1)
    END                                          AS density_pct_of_design,
    r.last_census_date,
    l.created_at,
    l.updated_at
FROM public.agri_lots l
JOIN public.agri_plantations p ON p.id = l.plantation_id AND p.id_company = l.id_company
LEFT JOIN public.agri_variety_catalog v ON v.id = l.variety_id
LEFT JOIN LATERAL (
    SELECT count(*)::integer           AS active_rows,
           sum(x.planting_positions)::integer AS planting_positions,
           sum(x.alive_plants)::integer       AS alive_plants,
           max(x.last_census_date)            AS last_census_date
      FROM public.agri_rows x
     WHERE x.lot_id = l.id AND x.id_company = l.id_company AND x.is_active
) r ON true
CROSS JOIN LATERAL (
    SELECT CASE WHEN l.planting_date IS NULL THEN NULL
                ELSE date_part('year', age(public.fn_agri_today_cdmx(), l.planting_date))::integer
           END AS age_years
) a;

