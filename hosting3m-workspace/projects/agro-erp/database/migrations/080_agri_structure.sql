-- 080_agri_structure.sql
-- Palm module, phase 1: organizational structure of an active plantation.
--   Company (companys) -> Plantation -> Lot -> Row -> plant count per row.
-- Several plantations per company. Individual plants, staff payments, inventory (assets/supplies),
-- FFB harvest, per-lot telemetry and per-user scope are later phases and are NOT created here.
--
-- Business rules (confirmed by the project owner):
--   * The security boundary is id_company. The active plantation is a UI scope filter only.
--   * Every child row carries the id_company of its parent: a BEFORE trigger rejects any mismatch
--     with a message that never reveals the other company, and a composite FK (parent_id, id_company)
--     makes the mismatch impossible at the database level even if the trigger were bypassed.
--   * Parents are immutable on a child (a lot never moves to another plantation, a row never moves
--     to another lot) and id_company never changes.
--   * A plantation / lot / row cannot be created or reactivated while its parent is inactive.
--   * Nothing is physically deleted: is_active = false. The CRUD models have no DELETE op.
--   * One active default plantation per company (partial unique index). The first active plantation
--     of a company becomes the default automatically; afterwards the default changes only through
--     sp_agri_set_default_plantation. Deactivating a plantation clears its default flag (the
--     frontend then falls back to another active plantation).
--   * alive_plants and planting_positions change only through sp_agri_record_row_census: the count is a
--     field operation (ADMIN, OWNER and EDITOR); changing the planting positions is ADMIN / OWNER only.
--     Rows are created only through sp_agri_bulk_create_rows (a single row is from_row = to_row).
--     Structure (plantations, lots, rows) is written by ADMIN / OWNER.
--   * Every change of planting_positions / alive_plants is logged in agri_row_census_history
--     (append-only) with a reason and the actor, same pattern as trg_log_identifier_changes. A CENSO that
--     confirms unchanged numbers is logged too (previous = new), written by the procedure itself.
--   * A lot may override the plantation's tenure (tenure / lessor_name NULL = inherited); the lot summary
--     exposes effective_tenure / effective_lessor_name.
--   * Timestamps are naive UTC (`timestamp`, now() AT TIME ZONE 'UTC'); "today" for date checks is
--     America/Mexico_City.
--
-- Gateway notes (v6/CRUD):
--   * No agri_* model has `id` in allowed_fields, so the insert upsert (ON CONFLICT (id) DO UPDATE)
--     can never target an existing row: the id is always generated by the database. getone and update
--     still work by id: Build Query takes the primary key from body.id / fields.id without checking
--     allowed_fields, and update adds `AND id_company = <x-tenant-id>` to its WHERE (commit 1809a46).
--   * is_default, planting_positions, alive_plants and last_census_date are not in allowed_fields either:
--     they are read-only through the generic CRUD and change only through the procedures.
--   * The three procedures must be registered in spConfigByModel (Build Query); a parameter missing
--     from paramOrder is silently dropped (lesson from 071). The actor email is always taken from the
--     verified JWT by the gateway, never from the client.
--   * v5/CRUD never serves these models (its allowlist only admits the 9 hotel models).
--
-- Objects:
--   agri_variety_catalog         (new, global, no id_company)  seed: TENERA, DURA, HIBRIDO_OXG, OTRA_SIN_ESPECIFICAR
--   agri_plantations             (new)
--   agri_lots                    (new)
--   agri_rows                    (new)
--   agri_row_census_history      (new, append-only)
--   fn_agri_* / trg_agri_*       (new) guards, updated_at, census history, immutability
--   sp_agri_set_default_plantation(p_tenant_id, p_plantation_id, p_actor_email)
--   sp_agri_bulk_create_rows(p_tenant_id, p_lot_id, p_from_row, p_to_row, p_positions_per_row, p_actor_email)
--   sp_agri_record_row_census(p_tenant_id, p_row_id, p_alive_plants, p_reason, p_census_date, p_notes, p_actor_email,
--                             p_planting_positions DEFAULT NULL)
--   vw_agri_lot_summary, vw_agri_plantation_summary (new views, expose id_company and created_at)
--   crud_models: 10 agri_* models (upsert ON CONFLICT (model_name)); PalmTelemetry: DELETE removed,
--                UPDATE only ADMIN (backed up first, restored by the rollback)
--
-- Error codes (messages in Spanish, shown as-is by the UI):
--   P0080  record not found or not in the active company (never says which company owns it)
--   P0081  parent (company / plantation / lot) is inactive
--   P0082  immutable column changed (id_company, plantation_id, lot_id)
--   P0083  date in the future (planting date, census date)
--   P0084  role not allowed for the operation (incl. an EDITOR changing planting positions)
--   P0085  invalid row range or size (bulk creation)
--   P0086  row range overlaps active rows (bulk creation)
--   P0087  invalid census (count or positions out of range, invalid reason, alive_plants / planting_positions
--          changed outside the procedure)
--   P0088  default plantation: target inactive, or is_default changed outside the procedure
--   P0089  agri_row_census_history is append-only
--
-- Rollback: 080_rollback.sql (no DROP / DELETE: disables the agri_* models and restores PalmTelemetry).
-- State:    080_state_check.sql -v expect=before|applied|rolled_back (read-only).
--
-- Usage (dry run is the default when apply is not given):
--   psql -v ON_ERROR_STOP=1 -f 080_agri_structure.sql                 -> dry run
--   psql -v ON_ERROR_STOP=1 -v apply=false -f 080_agri_structure.sql  -> dry run
--   psql -v ON_ERROR_STOP=1 -v apply=true  -f 080_agri_structure.sql  -> commit
-- 080_tests.sql includes this file with `embedded` set: it then neither opens nor ends the transaction
-- (the tests own it and always roll it back).

