-- 7) Guards -----------------------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.fn_agri_plantation_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_company_active boolean;
BEGIN
    IF TG_OP = 'UPDATE' AND NEW.id_company IS DISTINCT FROM OLD.id_company THEN
        RAISE EXCEPTION 'La empresa de una plantación no se puede cambiar.' USING ERRCODE = 'P0082';
    END IF;

    -- Creating or reactivating requires an active company.
    IF NEW.is_active AND (TG_OP = 'INSERT' OR NOT OLD.is_active) THEN
        SELECT c.is_active INTO v_company_active FROM public.companys c WHERE c.id_company = NEW.id_company;
        IF v_company_active IS FALSE THEN
            RAISE EXCEPTION 'La empresa está inactiva: no se pueden registrar ni reactivar plantaciones.'
                USING ERRCODE = 'P0081';
        END IF;
    END IF;

    IF TG_OP = 'INSERT' THEN
        -- The client never decides the default: the first active plantation of the company is the default.
        NEW.is_default := NEW.is_active AND NOT EXISTS (
            SELECT 1 FROM public.agri_plantations p
             WHERE p.id_company = NEW.id_company AND p.is_default AND p.is_active);
        RETURN NEW;
    END IF;

    IF NOT NEW.is_active THEN
        NEW.is_default := false;   -- an inactive plantation is never the default
    ELSIF NEW.is_default IS DISTINCT FROM OLD.is_default
          AND public.fn_agri_setting('app.agri_default_change') IS DISTINCT FROM 'on' THEN
        RAISE EXCEPTION 'La plantación predeterminada solo se cambia con "Hacer predeterminada".'
            USING ERRCODE = 'P0088';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_agri_lot_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_plantation record;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.id_company IS DISTINCT FROM OLD.id_company THEN
            RAISE EXCEPTION 'La empresa de un lote no se puede cambiar.' USING ERRCODE = 'P0082';
        END IF;
        IF NEW.plantation_id IS DISTINCT FROM OLD.plantation_id THEN
            RAISE EXCEPTION 'Un lote no se puede mover a otra plantación: desactívalo y regístralo en la otra.'
                USING ERRCODE = 'P0082';
        END IF;
    END IF;

    SELECT p.id_company, p.is_active INTO v_plantation
      FROM public.agri_plantations p WHERE p.id = NEW.plantation_id;
    IF NOT FOUND OR v_plantation.id_company IS DISTINCT FROM NEW.id_company THEN
        RAISE EXCEPTION 'La plantación no existe o no pertenece a la empresa activa.' USING ERRCODE = 'P0080';
    END IF;

    IF NEW.is_active AND (TG_OP = 'INSERT' OR NOT OLD.is_active) AND NOT v_plantation.is_active THEN
        RAISE EXCEPTION 'La plantación está inactiva: reactívala antes de registrar o reactivar lotes.'
            USING ERRCODE = 'P0081';
    END IF;

    IF NEW.planting_date IS NOT NULL AND NEW.planting_date > public.fn_agri_today_cdmx() THEN
        RAISE EXCEPTION 'La fecha de siembra no puede ser futura.' USING ERRCODE = 'P0083';
    END IF;

    IF NEW.variety_id IS NOT NULL
       AND (TG_OP = 'INSERT' OR NEW.variety_id IS DISTINCT FROM OLD.variety_id)
       AND NOT EXISTS (SELECT 1 FROM public.agri_variety_catalog v WHERE v.id = NEW.variety_id AND v.is_active) THEN
        RAISE EXCEPTION 'La variedad no existe o está dada de baja en el catálogo.' USING ERRCODE = 'P0080';
    END IF;
    RETURN NEW;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_agri_row_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_lot record;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.id_company IS DISTINCT FROM OLD.id_company THEN
            RAISE EXCEPTION 'La empresa de una fila no se puede cambiar.' USING ERRCODE = 'P0082';
        END IF;
        IF NEW.lot_id IS DISTINCT FROM OLD.lot_id THEN
            RAISE EXCEPTION 'Una fila no se puede mover a otro lote.' USING ERRCODE = 'P0082';
        END IF;
        -- sp_agri_record_row_census is the only way to change the live count and the planting positions.
        IF (NEW.alive_plants IS DISTINCT FROM OLD.alive_plants
            OR NEW.planting_positions IS DISTINCT FROM OLD.planting_positions)
           AND public.fn_agri_setting('app.agri_census_reason') IS NULL THEN
            RAISE EXCEPTION 'Las plantas vivas y los puntos de plantación solo se actualizan con "Registrar conteo".'
                USING ERRCODE = 'P0087';
        END IF;
    END IF;

    SELECT l.id_company, l.is_active AS lot_active, p.is_active AS plantation_active INTO v_lot
      FROM public.agri_lots l
      JOIN public.agri_plantations p ON p.id = l.plantation_id AND p.id_company = l.id_company
     WHERE l.id = NEW.lot_id;
    IF NOT FOUND OR v_lot.id_company IS DISTINCT FROM NEW.id_company THEN
        RAISE EXCEPTION 'El lote no existe o no pertenece a la empresa activa.' USING ERRCODE = 'P0080';
    END IF;

    IF NEW.is_active AND (TG_OP = 'INSERT' OR NOT OLD.is_active)
       AND NOT (v_lot.lot_active AND v_lot.plantation_active) THEN
        RAISE EXCEPTION 'El lote o su plantación están inactivos: reactívalos antes de registrar o reactivar filas.'
            USING ERRCODE = 'P0081';
    END IF;

    IF TG_OP = 'INSERT' THEN
        -- A new row starts with every planting position alive (alive_plants is not writable by the client).
        NEW.alive_plants := coalesce(NEW.alive_plants, NEW.planting_positions);
    END IF;

    IF NEW.last_census_date IS NOT NULL AND NEW.last_census_date > public.fn_agri_today_cdmx() THEN
        RAISE EXCEPTION 'La fecha del conteo no puede ser futura.' USING ERRCODE = 'P0083';
    END IF;
    RETURN NEW;
END;
$$;

-- Automatic census history (same pattern as trg_log_identifier_changes).
CREATE OR REPLACE FUNCTION public.fn_agri_row_census_history()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_reason text;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_reason := 'ALTA';
    ELSIF NEW.planting_positions IS DISTINCT FROM OLD.planting_positions
          OR NEW.alive_plants IS DISTINCT FROM OLD.alive_plants THEN
        v_reason := coalesce(public.fn_agri_setting('app.agri_census_reason'), 'CORRECCION_CAPTURA');
    ELSE
        RETURN NULL;
    END IF;

    INSERT INTO public.agri_row_census_history
        (row_id, id_company, previous_positions, new_positions, previous_alive, new_alive, reason, changed_by, notes)
    VALUES
        (NEW.id, NEW.id_company,
         CASE WHEN TG_OP = 'UPDATE' THEN OLD.planting_positions END, NEW.planting_positions,
         CASE WHEN TG_OP = 'UPDATE' THEN OLD.alive_plants END, NEW.alive_plants,
         v_reason,
         public.fn_agri_setting('app.agri_census_user'),
         public.fn_agri_setting('app.agri_census_notes'));
    RETURN NULL;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_agri_census_history_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP IN ('UPDATE', 'DELETE', 'TRUNCATE') THEN
        RAISE EXCEPTION 'El historial de conteos es de solo inserción.' USING ERRCODE = 'P0089';
    END IF;
    -- INSERT: the history row belongs to the company of its row (the composite FK enforces it too).
    IF NOT EXISTS (SELECT 1 FROM public.agri_rows r WHERE r.id = NEW.row_id AND r.id_company = NEW.id_company) THEN
