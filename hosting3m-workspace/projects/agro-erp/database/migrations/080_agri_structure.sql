CREATE OR REPLACE FUNCTION public.sp_agri_set_default_plantation(
    p_tenant_id      integer,
    p_plantation_id  uuid,
    p_actor_email    varchar
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    v_role      text := public.fn_agri_actor_role(p_tenant_id, p_actor_email);
    v_target    record;
    v_previous  uuid;
BEGIN
    IF v_role IS NULL OR v_role NOT IN ('ADMIN', 'OWNER') THEN
        RAISE EXCEPTION 'Solo un administrador de la empresa puede cambiar la plantación predeterminada.'
            USING ERRCODE = 'P0084';
    END IF;

    -- Serialize default changes of the company.
    PERFORM 1 FROM public.agri_plantations WHERE id_company = p_tenant_id FOR UPDATE;

    SELECT id, is_active, is_default INTO v_target
      FROM public.agri_plantations WHERE id = p_plantation_id AND id_company = p_tenant_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La plantación no existe o no pertenece a la empresa activa.' USING ERRCODE = 'P0080';
    END IF;
    IF NOT v_target.is_active THEN
        RAISE EXCEPTION 'Solo una plantación activa puede ser la predeterminada.' USING ERRCODE = 'P0088';
    END IF;

    SELECT id INTO v_previous FROM public.agri_plantations
     WHERE id_company = p_tenant_id AND is_default AND is_active;
    IF v_target.is_default THEN
        RETURN jsonb_build_object('success', true, 'changed', false, 'plantation_id', p_plantation_id);
    END IF;

    PERFORM set_config('app.agri_default_change', 'on', true);
    UPDATE public.agri_plantations SET is_default = false
     WHERE id_company = p_tenant_id AND is_default AND id <> p_plantation_id;
    UPDATE public.agri_plantations SET is_default = true WHERE id = p_plantation_id;
    PERFORM set_config('app.agri_default_change', '', true);

    RETURN jsonb_build_object('success', true, 'changed', true,
                              'plantation_id', p_plantation_id, 'previous_default_id', v_previous);
END;
$$;
COMMENT ON FUNCTION public.sp_agri_set_default_plantation(integer, uuid, varchar) IS
  'Makes an active plantation the default of the company (ADMIN/OWNER). Errors: P0080, P0084, P0088.';

CREATE OR REPLACE FUNCTION public.sp_agri_bulk_create_rows(
    p_tenant_id          integer,
    p_lot_id             uuid,
    p_from_row           integer,
    p_to_row             integer,
    p_positions_per_row  integer,
    p_actor_email        varchar
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    c_max_rows       constant integer := 500;
    c_max_positions  constant integer := 10000;
    v_role           text := public.fn_agri_actor_role(p_tenant_id, p_actor_email);
    v_lot            record;
    v_overlap        integer;
    v_examples       text;
    v_created        integer;
BEGIN
    IF v_role IS NULL OR v_role NOT IN ('ADMIN', 'OWNER') THEN
        RAISE EXCEPTION 'Solo un administrador de la empresa puede dar de alta filas.' USING ERRCODE = 'P0084';
    END IF;
    IF p_from_row IS NULL OR p_to_row IS NULL OR p_from_row < 1 OR p_to_row < p_from_row THEN
        RAISE EXCEPTION 'El rango de filas no es válido: la fila inicial debe ser 1 o mayor y no mayor que la final.'
            USING ERRCODE = 'P0085';
    END IF;
    IF p_to_row - p_from_row + 1 > c_max_rows THEN
        RAISE EXCEPTION 'Máximo % filas por alta masiva (pediste %).', c_max_rows, p_to_row - p_from_row + 1
            USING ERRCODE = 'P0085';
    END IF;
    IF p_positions_per_row IS NULL OR p_positions_per_row < 0 OR p_positions_per_row > c_max_positions THEN
        RAISE EXCEPTION 'Los puntos de plantación por fila deben estar entre 0 y %.', c_max_positions
            USING ERRCODE = 'P0085';
    END IF;

    SELECT l.id, l.is_active AS lot_active, p.is_active AS plantation_active INTO v_lot
      FROM public.agri_lots l
      JOIN public.agri_plantations p ON p.id = l.plantation_id AND p.id_company = l.id_company
     WHERE l.id = p_lot_id AND l.id_company = p_tenant_id
       FOR UPDATE OF l;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El lote no existe o no pertenece a la empresa activa.' USING ERRCODE = 'P0080';
    END IF;
    IF NOT (v_lot.lot_active AND v_lot.plantation_active) THEN
        RAISE EXCEPTION 'El lote o su plantación están inactivos.' USING ERRCODE = 'P0081';
    END IF;

    SELECT count(*), string_agg(row_number::text, ', ' ORDER BY row_number) FILTER (WHERE rn <= 10)
      INTO v_overlap, v_examples
      FROM (SELECT r.row_number, row_number() OVER (ORDER BY r.row_number) AS rn
              FROM public.agri_rows r
             WHERE r.lot_id = p_lot_id AND r.is_active AND r.row_number BETWEEN p_from_row AND p_to_row) s;
    IF v_overlap > 0 THEN
        RAISE EXCEPTION 'Ya existen % fila(s) activa(s) en ese rango (%). No se creó ninguna.',
            v_overlap, v_examples || CASE WHEN v_overlap > 10 THEN ', …' ELSE '' END
            USING ERRCODE = 'P0086';
    END IF;

    PERFORM set_config('app.agri_census_user', lower(btrim(p_actor_email)), true);
    PERFORM set_config('app.agri_census_notes',
        CASE WHEN p_from_row = p_to_row THEN format('Alta de fila %s', p_from_row)
             ELSE format('Alta masiva de filas %s a %s', p_from_row, p_to_row) END, true);
    INSERT INTO public.agri_rows (id_company, lot_id, row_number, planting_positions)
    SELECT p_tenant_id, p_lot_id, n, p_positions_per_row
      FROM generate_series(p_from_row, p_to_row) AS n;
    GET DIAGNOSTICS v_created = ROW_COUNT;
    PERFORM set_config('app.agri_census_user', '', true);
    PERFORM set_config('app.agri_census_notes', '', true);

    RETURN jsonb_build_object('success', true, 'created', v_created,
                              'from_row', p_from_row, 'to_row', p_to_row,
                              'positions_per_row', p_positions_per_row);
END;
$$;
COMMENT ON FUNCTION public.sp_agri_bulk_create_rows(integer, uuid, integer, integer, integer, varchar) IS
  'Creates consecutive rows (alive = positions), max 500 per call, rejecting overlaps with active rows (ADMIN/OWNER). Errors: P0080, P0081, P0084, P0085, P0086.';

CREATE OR REPLACE FUNCTION public.sp_agri_record_row_census(
    p_tenant_id           integer,
    p_row_id              uuid,
    p_alive_plants        integer,
    p_reason              varchar,
    p_census_date         date,
    p_notes               text,
    p_actor_email         varchar,
    p_planting_positions  integer DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
AS $$
DECLARE
    c_max_positions  constant integer := 10000;
    v_role           text := public.fn_agri_actor_role(p_tenant_id, p_actor_email);
    v_actor          text := lower(btrim(coalesce(p_actor_email, '')));
    v_reason         text := upper(btrim(coalesce(p_reason, 'CENSO')));
    v_date           date := coalesce(p_census_date, public.fn_agri_today_cdmx());
    v_row            record;
    v_positions      integer;
    v_changed        boolean;
BEGIN
    -- Field operation: the foreman (EDITOR) must be able to record counts (event authorization matrix).
    IF v_role IS NULL OR v_role NOT IN ('ADMIN', 'OWNER', 'EDITOR') THEN
        RAISE EXCEPTION 'Tu rol en la empresa no permite registrar conteos.' USING ERRCODE = 'P0084';
    END IF;
    IF v_reason NOT IN ('CENSO', 'RESIEMBRA', 'PERDIDA', 'CORRECCION_CAPTURA') THEN
        RAISE EXCEPTION 'Motivo no válido: usa CENSO, RESIEMBRA, PERDIDA o CORRECCION_CAPTURA.' USING ERRCODE = 'P0087';
    END IF;
    IF v_date > public.fn_agri_today_cdmx() THEN
        RAISE EXCEPTION 'La fecha del conteo no puede ser futura.' USING ERRCODE = 'P0083';
    END IF;

    SELECT r.id, r.planting_positions, r.alive_plants, r.last_census_date, r.is_active,
           l.is_active AS lot_active, p.is_active AS plantation_active
      INTO v_row
      FROM public.agri_rows r
      JOIN public.agri_lots l ON l.id = r.lot_id AND l.id_company = r.id_company
      JOIN public.agri_plantations p ON p.id = l.plantation_id AND p.id_company = l.id_company
     WHERE r.id = p_row_id AND r.id_company = p_tenant_id
       FOR UPDATE OF r;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'La fila no existe o no pertenece a la empresa activa.' USING ERRCODE = 'P0080';
    END IF;
    IF NOT (v_row.is_active AND v_row.lot_active AND v_row.plantation_active) THEN
        RAISE EXCEPTION 'La fila, su lote o su plantación están inactivos.' USING ERRCODE = 'P0081';
    END IF;

    -- Planting positions: optional; only ADMIN / OWNER may change them (EDITOR changes alive_plants only).
    v_positions := coalesce(p_planting_positions, v_row.planting_positions);
    IF v_positions < 0 OR v_positions > c_max_positions THEN
        RAISE EXCEPTION 'Los puntos de plantación deben estar entre 0 y %.', c_max_positions USING ERRCODE = 'P0087';
    END IF;
    IF v_positions <> v_row.planting_positions AND v_role NOT IN ('ADMIN', 'OWNER') THEN
        RAISE EXCEPTION 'Solo un administrador de la empresa puede cambiar los puntos de plantación de una fila.'
            USING ERRCODE = 'P0084';
    END IF;
    -- Validated against the FINAL values.
    IF p_alive_plants IS NULL OR p_alive_plants < 0 OR p_alive_plants > v_positions THEN
        RAISE EXCEPTION 'El conteo (%) debe estar entre 0 y los % puntos de plantación de la fila.',
            coalesce(p_alive_plants::text, 'vacío'), v_positions USING ERRCODE = 'P0087';
    END IF;

    v_changed := p_alive_plants <> v_row.alive_plants OR v_positions <> v_row.planting_positions;

    PERFORM set_config('app.agri_census_reason', v_reason, true);
    PERFORM set_config('app.agri_census_user', v_actor, true);
    PERFORM set_config('app.agri_census_notes', coalesce(p_notes, ''), true);
    -- When something changes, trg_agri_rows_census_history writes the history row (reason + actor above).
    UPDATE public.agri_rows
       SET planting_positions = v_positions,
           alive_plants = p_alive_plants,
           last_census_date = greatest(coalesce(last_census_date, v_date), v_date)
     WHERE id = p_row_id;
    PERFORM set_config('app.agri_census_reason', '', true);
    PERFORM set_config('app.agri_census_user', '', true);
    PERFORM set_config('app.agri_census_notes', '', true);

    -- A CENSO that confirms the same numbers still leaves a record (previous = new). Written here, only when
    -- nothing changed, so it never duplicates the trigger's row.
    IF NOT v_changed AND v_reason = 'CENSO' THEN
        INSERT INTO public.agri_row_census_history
            (row_id, id_company, previous_positions, new_positions, previous_alive, new_alive, reason, changed_by, notes)
        VALUES
            (p_row_id, p_tenant_id, v_positions, v_positions, p_alive_plants, p_alive_plants,
             'CENSO', NULLIF(v_actor, ''), NULLIF(p_notes, ''));
    END IF;

    RETURN jsonb_build_object('success', true, 'row_id', p_row_id, 'reason', v_reason, 'census_date', v_date,
                              'previous_alive', v_row.alive_plants, 'alive_plants', p_alive_plants,
                              'previous_positions', v_row.planting_positions, 'planting_positions', v_positions,
                              'changed', v_changed);
END;
$$;
COMMENT ON FUNCTION public.sp_agri_record_row_census(integer, uuid, integer, varchar, date, text, varchar, integer) IS
  'Only way to update alive_plants and planting_positions (count: ADMIN/OWNER/EDITOR; positions: ADMIN/OWNER). History via trg_agri_rows_census_history, plus an explicit CENSO row when a census confirms unchanged numbers. Errors: P0080, P0081, P0083, P0084, P0087.';

