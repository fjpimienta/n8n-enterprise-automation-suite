#!/usr/bin/env python3
"""108_make_reenable.py: generates 108_reenable.sql from 108_palpation_views.sql. It never retypes a value: every restored literal is
copied verbatim from the INSERT INTO public.crud_models of the migration, and the column names come from that INSERT's column list.

  python3 -I 108_make_reenable.py          rewrites 108_reenable.sql
  python3 -I 108_make_reenable.py --check  regenerates in memory and exits 1 if the committed 108_reenable.sql differs (used by 108_static_check.sh)

The fingerprints the reenable must reproduce are the ones printed by the apply of 108_palpation_views.sql (per model row: md5 of row_to_json of the
15 columns, the same formula as 108_state_check.sql). They are constants here, and the LOCAL test proves they are the ones the apply produces.
"""
import pathlib, re, sys

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / '108_reenable.sql'
MIG = HERE / '108_palpation_views.sql'
EXPECTED_FP = {          # printed by the apply (same row content, same formula)
    'vw_palpation_events': '51b93c8cc669c0cb8bb722d874790438',
    'vw_palpation_herd': '7d0209677c2bd1189fbdc35792bf4599',
}
RESTORED = ['allowed_ops', 'allowed_roles_select', 'allowed_roles_insert', 'allowed_roles_update', 'allowed_roles_delete', 'joins', 'is_global', 'sp_requires_tenant']


def migration_rows():
    sql = MIG.read_text(encoding='utf-8')
    head = re.search(r'INSERT INTO public\.crud_models \(([^)]*)\)\s*VALUES(.*?);', sql, re.S)
    if not head:
        sys.exit('ABORT: INSERT INTO public.crud_models not found in 108_palpation_views.sql')
    cols = [c.strip() for c in head.group(1).replace('\n', ' ').split(',')]
    tokens = re.findall(r"'[^']*'|\bNULL\b|\btrue\b|\bfalse\b", head.group(2))
    if len(cols) != 15 or len(tokens) != 30:
        sys.exit(f'ABORT: expected 15 columns and 2 rows of 15 values, got {len(cols)} columns and {len(tokens)} values')
    rows = {}
    for i in range(2):
        vals = dict(zip(cols, tokens[i * 15:(i + 1) * 15]))
        rows[vals['model_name'].strip("'")] = (cols, vals)
    return cols, rows


def generate():
    cols, rows = migration_rows()
    if set(rows) != set(EXPECTED_FP):
        sys.exit(f'ABORT: models in the migration {sorted(rows)} differ from {sorted(EXPECTED_FP)}')
    fp_cols = ', '.join(cols)
    out = []
    out.append('-- 108_reenable.sql: GENERATED by 108_make_reenable.py from 108_palpation_views.sql. Do not edit by hand.')
    out.append('-- Inverse of 108_rollback.sql for the two palpation models: restores allowed_ops, the four roles, joins, is_global and')
    out.append('-- sp_requires_tenant from the migration, only on rows that are in the REVERTED state. No INSERT, no DELETE, no DROP.')
    out.append('-- The apply-time fingerprints are checked AFTER the restore and BEFORE the commit: a mismatch aborts the transaction.')
    out.append('-- Usage (dry run is the default, rolled back):')
    out.append('--   psql -X -v ON_ERROR_STOP=1 -f 108_reenable.sql')
    out.append('--   psql -X -v ON_ERROR_STOP=1 -v apply=true -f 108_reenable.sql')
    out.append('-- Then: 108_state_check.sql -v expect=applied  (model_rows must be 888bab6298cecf8df9899212cd713f05)')
    out.append('')
    out.append('\\set ON_ERROR_STOP on')
    out.append('\\if :{?apply}')
    out.append('\\else')
    out.append('\\set apply false')
    out.append('\\endif')
    out.append('\\if :{?embedded}')
    out.append('\\else')
    out.append('BEGIN;')
    out.append('\\endif')
    out.append('')
    out.append('-- 0) Preconditions: both views exist and both models are in the reverted state (allowed_ops {} and every role NONE)')
    out.append('DO $$')
    out.append('DECLARE v_reverted integer;')
    out.append('BEGIN')
    out.append("    IF to_regclass('public.vw_palpation_events') IS NULL OR to_regclass('public.vw_palpation_herd') IS NULL THEN")
    out.append("        RAISE EXCEPTION 'ABORT: the two palpation views do not exist. Nothing to re-enable.';")
    out.append('    END IF;')
    out.append("    IF (SELECT count(*) FROM public.crud_models WHERE model_name IN ('vw_palpation_events', 'vw_palpation_herd')) <> 2 THEN")
    out.append("        RAISE EXCEPTION 'ABORT: expected exactly the two palpation model rows.';")
    out.append('    END IF;')
    out.append("    SELECT count(*) INTO v_reverted FROM public.crud_models")
    out.append("     WHERE model_name IN ('vw_palpation_events', 'vw_palpation_herd')")
    out.append("       AND allowed_ops = '{}' AND allowed_roles_select = 'NONE' AND allowed_roles_insert = 'NONE'")
    out.append("       AND allowed_roles_update = 'NONE' AND allowed_roles_delete = 'NONE';")
    out.append('    IF v_reverted <> 2 THEN')
    out.append("        RAISE EXCEPTION 'ABORT: only % of 2 models are in the reverted state (allowed_ops {} and roles NONE). Already enabled or changed by hand: not touching it.', v_reverted;")
    out.append('    END IF;')
    out.append('END $$;')
    out.append('')
    out.append('-- 1) Restore (one guarded UPDATE per model; values copied from the migration)')
    for name in ('vw_palpation_events', 'vw_palpation_herd'):
        _, vals = rows[name]
        sets = ',\n       '.join(f'{c} = {vals[c]}' for c in RESTORED)
        out.append(f"UPDATE public.crud_models SET {sets}")
        out.append(f"       WHERE model_name = '{name}'")
        out.append("         AND allowed_ops = '{}' AND allowed_roles_select = 'NONE' AND allowed_roles_insert = 'NONE'")
        out.append("         AND allowed_roles_update = 'NONE' AND allowed_roles_delete = 'NONE';")
    out.append('')
    out.append('-- 2) Fingerprints of the two model rows: must equal the ones printed by the apply, or the transaction is aborted (nothing committed)')
    out.append('DO $$')
    out.append('DECLARE v_e text; v_h text;')
    out.append('BEGIN')
    for name, var in (('vw_palpation_events', 'v_e'), ('vw_palpation_herd', 'v_h')):
        out.append(f"    SELECT md5(row_to_json(c)::text) INTO {var} FROM (SELECT {fp_cols} FROM public.crud_models WHERE model_name = '{name}') c;")
    out.append("    RAISE NOTICE 'model vw_palpation_events %', v_e;")
    out.append("    RAISE NOTICE 'model vw_palpation_herd %', v_h;")
    out.append(f"    IF v_e IS DISTINCT FROM '{EXPECTED_FP['vw_palpation_events']}' OR v_h IS DISTINCT FROM '{EXPECTED_FP['vw_palpation_herd']}' THEN")
    out.append("        RAISE EXCEPTION 'ABORT: a model row after the restore differs from the apply fingerprint (events %, herd %). Nothing committed.', v_e, v_h;")
    out.append('    END IF;')
    out.append('END $$;')
    out.append('')
    out.append('\\if :{?embedded}')
    out.append('\\else')
    out.append('\\if :apply')
    out.append('COMMIT;')
    out.append("\\echo '*** 108 RE-ENABLED (committed) ***'")
    out.append('\\else')
    out.append('ROLLBACK;')
    out.append("\\echo '*** 108 RE-ENABLE DRY RUN: rolled back, nothing changed ***'")
    out.append('\\endif')
    out.append('\\endif')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    text = generate()
    if '--check' in sys.argv:
        committed = OUT.read_text(encoding='utf-8') if OUT.exists() else ''
        if committed != text:
            print('FAIL  108_reenable.sql differs from the generator output (regenerate it)')
            sys.exit(1)
        print('OK    108_reenable.sql matches the generator and the migration')
    else:
        OUT.write_text(text, encoding='utf-8')
        print(f'wrote {OUT.name}')
